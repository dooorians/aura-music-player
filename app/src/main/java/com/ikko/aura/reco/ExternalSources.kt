/**
 * The sources the app already has, as candidate sources. Each uses only what the source really gives: YouTube Music's
 * search, its "up next" list and a song's page; JioSaavn's search, its "reco" list and the year it states; an added
 * Subsonic server's search and the year of its songs.
 */
@Singleton
class ExternalSources @Inject constructor(
    private val ytm: YtmClient,
    private val jioSaavn: JioSaavnClient,
    private val remote: RemoteSources,
) {
    suspend fun all(): List<CandidateSource> {
        val added = remote.active().map { RemoteCandidates(it.config.id, it.config.name, remote) }
        return listOf(YtmCandidates(ytm), JioSaavnCandidates(jioSaavn)) + added
    }
}

internal class YtmCandidates(private val client: YtmClient) : CandidateSource {
    override val id = "ytm"
    override val name = "YouTube Music"

    override suspend fun available(): Boolean = withContext(Dispatchers.IO) { client.isEnabled() }

    private fun candidateOf(song: YtmSong, provenance: Provenance) = Candidate(
        id = YtmLibrary.keyOf(song.videoId),
        sourceId = id,
        sourceName = name,
        title = song.title,
        artist = song.artist,
        album = song.albumTitle.orEmpty(),
        durationMs = song.durationMs,
        artworkUrl = song.thumbnailUrl,
        // A search gives no date: it is looked up on the song's page, for the few that could be new.
        release = Release.Unknown,
        provenance = listOf(provenance),
        albumRef = song.albumId,
        confirmedSong = song.isSong,
    )

    override suspend fun search(query: String, provenance: Provenance): List<Candidate> = withContext(Dispatchers.IO) {
        val songs = client.search(query).songs
        // A search for an artist also returns covers and songs that merely mention them, and namesakes ("Lisa" is not "Lisa Ono"): that artist only.
        val wanted = if (provenance.kind == ProvKind.ARTIST) ArtistNames.key(provenance.seed) else null
        songs.filter { s -> wanted == null || ArtistNames.key(s.artist) == wanted || wanted in ArtistNames.split(s.artist) }
            .map { candidateOf(it, provenance) }
    }

    override suspend fun related(title: String, artist: String, provenance: Provenance): List<Candidate> = withContext(Dispatchers.IO) {
        val wanted = TrackIdentity.titleKey(title)
        val seed = client.search("$artist $title").songs.firstOrNull { TrackIdentity.titleKey(it.title) == wanted }
            ?: return@withContext emptyList()
        client.related(seed.videoId).map { candidateOf(it, provenance) }
    }

    override suspend fun verify(candidate: Candidate): Verification = withContext(Dispatchers.IO) {
        try {
            val d = client.details(candidate.id.substringAfter(':'))
            Verification(
                playable = d.playable,
                release = d.releasedOn?.let { Release.ofDate(it) },
                tags = listOfNotNull(d.category) + d.tags.take(8),
                album = d.album,
                isSong = d.autoGenerated,
                artists = d.artists,
            )
        } catch (e: IOException) {
            Verification(null)
        } catch (e: org.schabi.newpipe.extractor.exceptions.ExtractionException) {
            // The page could not be read (a changed layout, a refused request): not "cannot be played".
            Verification(null)
        }
    }
}

internal class JioSaavnCandidates(private val client: JioSaavnClient) : CandidateSource {
    override val id = "jiosaavn"
    override val name = "JioSaavn"

    override suspend fun available(): Boolean = true

    private fun candidateOf(raw: RawSongItem, provenance: Provenance): Candidate {
        val track = JioSaavnTracks.trackOf(raw)
        val date = raw.moreInfo.releaseDate?.let { runCatching { LocalDate.parse(it.take(10)) }.getOrNull() }
        val year = raw.year.toIntOrNull() ?: 0
        return Candidate(
            id = track.id,
            sourceId = id,
            sourceName = name,
            title = track.title,
            artist = track.artist,
            album = track.album,
            durationMs = track.durationMs,
            artworkUrl = track.artworkUri?.toString(),
            extraCredits = raw.moreInfo.artistMap.featuredArtists.map { JioSaavnTracks.unescape(it.name) },
            release = date?.let { Release.ofDate(it) } ?: Release.ofYear(year),
            tags = listOf(raw.language).filter { it.isNotBlank() },
            provenance = listOf(provenance),
        )
    }

    override suspend fun search(query: String, provenance: Provenance): List<Candidate> {
        val wanted = if (provenance.kind == ProvKind.ARTIST) ArtistNames.key(provenance.seed) else null
        return client.searchSongsOrThrow(query)
            .filter { raw -> wanted == null || ArtistNames.split(JioSaavnTracks.artistOf(raw)).any { it == wanted } }
            .map { candidateOf(it, provenance) }
    }

    override suspend fun related(title: String, artist: String, provenance: Provenance): List<Candidate> {
        val wanted = TrackIdentity.titleKey(title)
        val seed = client.searchSongsOrThrow("$artist $title")
            .firstOrNull { TrackIdentity.titleKey(JioSaavnTracks.unescape(it.title)) == wanted } ?: return emptyList()
        return client.recommendationsOrThrow(seed.id).map { candidateOf(it, provenance) }
    }

    override suspend fun verify(candidate: Candidate): Verification {
        val stream = try { client.getStreamUrl(candidate.id.substringAfter(':')) } catch (e: IOException) { return Verification(null) }
        return Verification(playable = stream != null)
    }
}

internal class RemoteCandidates(
    override val id: String,
    override val name: String,
    private val remote: RemoteSources,
) : CandidateSource {

    override suspend fun available(): Boolean = remote.client(id) != null

    override suspend fun search(query: String, provenance: Provenance): List<Candidate> = withContext(Dispatchers.IO) {
        val client = remote.client(id) ?: return@withContext emptyList()
        val wanted = if (provenance.kind == ProvKind.ARTIST) ArtistNames.key(provenance.seed) else null
        client.search(query).songs
            .filter { s -> wanted == null || ArtistNames.split(s.artist).any { it == wanted } }
            .map { s ->
                val track = RemoteTracks.trackOf(id, s, client)
                Candidate(
                    id = track.id, sourceId = id, sourceName = name, title = s.title, artist = s.artist, album = s.album,
                    durationMs = s.durationMs, artworkUrl = track.artworkUri?.toString(),
                    release = Release.ofYear(s.year), provenance = listOf(provenance),
                    albumRef = track.remoteAlbumId,
                    // The server listed it: its own file, not a guess.
                    playability = Playability.VERIFIED,
                )
            }
    }

    override suspend fun related(title: String, artist: String, provenance: Provenance): List<Candidate> = emptyList()

    override suspend fun verify(candidate: Candidate): Verification = Verification(playable = remote.client(id) != null)
}

/** The [Track] the app plays for a candidate of any source. */
fun Candidate.toTrack(): Track = when (sourceId) {
    "ytm" -> YtmLibrary.trackOf(
        videoId = id.substringAfter(':'), title = title, artist = artist, durationMs = durationMs,
        thumbnailUrl = artworkUrl, albumId = albumRef, albumTitle = album.ifBlank { null },
    )
    "jiosaavn" -> Track(
        id = id, title = title, artist = artist, album = album, artistId = 0L,
        albumId = com.ikko.aura.source.jiosaavn.jioSaavnAlbumId("", id.substringAfter(':')),
        artworkUri = artworkUrl?.let(android.net.Uri::parse),
        contentUri = android.net.Uri.parse("jiosaavn://${id.substringAfter(':')}"),
        durationMs = durationMs, year = release.year,
        bitrateKbps = 320, sampleRateHz = 44100, bitDepth = 16,
    )
    else -> RemoteTracks.trackOf(
        key = id, title = title, artist = artist, durationMs = durationMs, artworkUrl = artworkUrl,
        albumRef = albumRef, albumTitle = album.ifBlank { null }, year = release.year,
    )
}

/** The [Track] of a stored recommendation. */
object RecoItemTracks {
    fun RecoItem.toTrack(): Track = Candidate(
        id = trackId, sourceId = sourceId, sourceName = sourceName, title = title, artist = artist, album = album,
        durationMs = durationMs, artworkUrl = artworkUrl.ifEmpty { null }, albumRef = albumRef.ifEmpty { null },
    ).toTrack()
}
