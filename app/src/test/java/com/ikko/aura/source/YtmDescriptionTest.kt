package com.ikko.aura.source

import com.ikko.aura.source.ytm.YtmClient
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YtmDescriptionTest {

    @Test fun `an official release names its album`() {
        // As YouTube writes it for "Hold The Girl" (HTML line breaks and all).
        val d = "Provided to YouTube by Virgin Music Group<br><br>Hold The Girl · Rina Sawayama<br><br>Hold The Girl" +
            "<br><br>℗ 2022 Dirty Hit<br><br>Released on: 2022-09-16<br><br>Producer: Barney Lister<br><br>Auto-generated by YouTube."
        val g = YtmClient.parseGenerated(d)
        assertTrue(g.autoGenerated)
        assertEquals("Hold The Girl", g.album)
        assertEquals(listOf("Rina Sawayama"), g.artists)
    }

    @Test fun `a video about a song is not an official release`() {
        val g = YtmClient.parseGenerated("Why does this chorus work so well? Let's break down the theory…")
        assertFalse(g.autoGenerated)
        assertNull(g.album)
        assertTrue(g.artists.isEmpty())
    }

    @Test fun `a release with no album line gives none`() {
        val g = YtmClient.parseGenerated("Provided to YouTube by X<br><br>Song · Artist<br><br>℗ 2022 Label<br><br>Released on: 2022-09-16")
        assertTrue(g.autoGenerated)
        assertNull(g.album)
    }

    @Test fun `a collaboration names every artist`() {
        val g = YtmClient.parseGenerated("Provided to YouTube by X<br><br>Beg for You (feat. Rina Sawayama) · Charli XCX · Rina Sawayama<br><br>Crash<br><br>℗ 2022")
        assertEquals(listOf("Charli XCX", "Rina Sawayama"), g.artists)
    }
}
